namespace LyricCanvas.Core;

/// <summary>
/// 歌词窗口的主行显示什么。
///
/// 这个软件虽然叫"歌词适配"，但它本质上是一个**桌面文字叠加层**——
/// 渲染、拖动、透明度、穿透锁定这些能力跟文字从哪来无关。
/// 所以把"文字来源"抽成一个开关，而不是写死成歌词。
///
/// 目前两种：
///   - 跟着系统播放的音乐显示歌词；
///   - 显示用户自己输入的一段文字（当字幕、座右铭、提示语都行）。
///
/// 以后要加"剪贴板""文本文件""多段轮播"之类，也是往这里加枚举值。
/// </summary>
public enum ContentMode
{
    /// <summary>显示当前播放歌曲的歌词。</summary>
    Lyrics = 0,

    /// <summary>显示用户自定义的固定文本。</summary>
    CustomText = 1,
}
